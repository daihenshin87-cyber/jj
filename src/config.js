export function detectDeviceGraphicsPreset() {
  if (typeof navigator === 'undefined' || typeof window === 'undefined') return 'medium';
  const isMobile = /Android|iPhone|iPad|iPod/i.test(navigator.userAgent || '') || ('ontouchstart' in window) || (navigator.maxTouchPoints > 0);
  const mem = navigator.deviceMemory || 4;
  const cores = navigator.hardwareConcurrency || 4;
  if (isMobile) return (mem <= 3 || cores <= 4) ? 'low' : 'medium';
  return (mem >= 8 && cores >= 6) ? 'high' : 'medium';
}

